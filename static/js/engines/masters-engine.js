    // ========== 五段式分析主函数 ==========
    /**
     * 生成五段式分析
     * @param {string} masterId - 大师ID
     * @param {Object} context - 辨证上下文（病位、病性、证型、症状、舌脉等）
     * @returns {Object} 五段式分析结果
     */
    function analyze(masterId, context) {
        var master = _findMaster(masterId);
        if (!master) return null;

        var ctx = context || {};
        var result = {
            master: master,
            opening: _generateOpening(master, ctx),
            overview: _generateOverview(master, ctx),
            specialty: _generateSpecialty(master, ctx),
            quote: _generateQuote(master, ctx),
            closing: _generateClosing(master, ctx)
        };
        return result;
    }

    /**
     * 查找大师
     */
    function _findMaster(id) {
        for (var i = 0; i < MASTERS.length; i++) {
            if (MASTERS[i].id === id) return MASTERS[i];
        }
        return null;
    }

    /**
     * 生成开篇
     */
    function _generateOpening(master, ctx) {
        var templates = master.openingTemplates;
        var template = templates[Math.floor(Math.random() * templates.length)];
        return _fillTemplate(template, ctx);
    }

    /**
     * 生成总论
     */
    function _generateOverview(master, ctx) {
        var templates = OVERVIEW_TEMPLATES[master.id] || OVERVIEW_TEMPLATES['zhangzhongjing'];
        var template = templates[Math.floor(Math.random() * templates.length)];
        return _fillTemplate(template, ctx);
    }

    /**
     * 生成专论
     */
    function _generateSpecialty(master, ctx) {
        var type = ctx.type || '辨证';
        var templates = SPECIALTY_TEMPLATES[type] || SPECIALTY_TEMPLATES['辨证'];
        var template = templates[Math.floor(Math.random() * templates.length)];
        return _fillTemplate(template, ctx);
    }

    /**
     * 生成经典引用
     */
    function _generateQuote(master, ctx) {
        var templates = master.quoteTemplates;
        var template = templates[Math.floor(Math.random() * templates.length)];
        return _fillTemplate(template, ctx);
    }

    /**
     * 生成结语
     */
    function _generateClosing(master, ctx) {
        var templates = master.closingTemplates;
        var template = templates[Math.floor(Math.random() * templates.length)];
        return _fillTemplate(template, ctx);
    }

