    /**
     * 主入口：本草查询
     */
    function query(name) {
        if (!name) return null;
        return BENCAO_DB[_findKey(name)] || null;
    }

    /**
     * 模糊搜索
     */
    function search(keyword) {
        if (!keyword) return [];
        return Object.keys(BENCAO_DB).filter(function(name) {
            return name.indexOf(keyword) !== -1;
        });
    }

    /**
     * 查找匹配key
     */
    function _findKey(name) {
        if (BENCAO_DB[name]) return name;
        var candidates = Object.keys(BENCAO_DB);
        for (var i = 0; i < candidates.length; i++) {
            if (candidates[i].indexOf(name) !== -1 || name.indexOf(candidates[i]) !== -1) {
                return candidates[i];
            }
        }
        return null;
    }

    // 功效反向索引
    var EFFECT_INDEX = {};
    Object.keys(BENCAO_DB).forEach(function(name) {
        var herb = BENCAO_DB[name];
        var effects = (herb.功效 || '').split(/[、，]/).map(function(s) { return s.trim(); });
        effects.forEach(function(effect) {
            if (effect) {
                if (!EFFECT_INDEX[effect]) EFFECT_INDEX[effect] = [];
                EFFECT_INDEX[effect].push(name);
            }
        });
    });

