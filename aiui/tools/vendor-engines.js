// 把岐黄阁原始引擎打包成 aiui/ 内部的 ES 模块。
//
// 为什么需要这一步（硬约束）：
//   · AIUI 打包成 .aix 只收工程根目录（aiui/）以内的文件，原始引擎在 ../../static 里，
//     在设备上 import 不进来
//   · 原始引擎是 IIFE（(function(global){...})(typeof global!=='undefined'?global:window)），
//     不会自己 export 任何东西
//   · 用户要求原始文件零改动
//
// 所以这里**只生成包装**：把原始源码原样放进一个函数体，给它一个局部对象当 global，
// 再把挂上去的 XxxEngine 导出来。原始文件一个字节都没改——tests/vendor-parity.js
// 会做两件事证明这一点：比 sha256 证明源文件没变，比查询结果证明包装没改变行为。
//
// 用法：node tools/vendor-engines.js

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const HERE = dirname(fileURLToPath(import.meta.url));
export const AIUI_ROOT = resolve(HERE, '..');
export const PROJECT_ROOT = resolve(AIUI_ROOT, '..');
export const VENDOR_DIR = join(AIUI_ROOT, 'vendor');

export function readManifest() {
  return JSON.parse(readFileSync(join(AIUI_ROOT, 'manifest.json'), 'utf8'));
}

const sha256 = (s) => createHash('sha256').update(s, 'utf8').digest('hex');

/** 从源码里找它往 global 上挂了什么名字 */
export function detectExportNames(source) {
  return [...source.matchAll(/global\.([A-Za-z_$][\w$]*)\s*=/g)].map((m) => m[1]);
}

function wrapper(rel, source, names) {
  const hash = sha256(source);
  const exports = names
    .map((n) => `export const ${n} = __scope.${n};`)
    .join('\n');
  return `// AUTO-GENERATED by tools/vendor-engines.js —— 不要手改，改源文件后重跑生成器。
// 源文件：${rel}
// 源文件 sha256：${hash}
//
// 为什么是这个形状：AIUI 打包只收 aiui/ 以内的文件，原始引擎在工程外且是 IIFE，
// 既不进来也不会 export。这里给它一个局部作用域当 global，再把挂载的对象导出来，
// 原文件内容逐字保留在函数体内，未做任何改写。
const __scope = {};
(function (global, window) {
${source}
})(__scope, __scope);

${exports}

export default __scope;
`;
}

/** 生成全部包装文件，返回生成清单 */
export function generate({ quiet = false } = {}) {
  const manifest = readManifest();
  mkdirSync(VENDOR_DIR, { recursive: true });

  const made = [];
  const missing = [];

  for (const rel of manifest.scripts) {
    const abs = join(PROJECT_ROOT, rel);
    if (!existsSync(abs)) {
      missing.push(rel);
      continue;
    }
    const source = readFileSync(abs, 'utf8');
    const names = detectExportNames(source);
    if (names.length === 0) {
      // 挂载名认不出来就不生成——宁可少一个文件，也不要生成一个导不出东西的空壳
      missing.push(`${rel}（没找到 global.XxxEngine 挂载）`);
      continue;
    }
    const file = join(VENDOR_DIR, basename(rel));
    writeFileSync(file, wrapper(rel, source, names), 'utf8');
    made.push({ rel, file: basename(file), names, sha256: sha256(source), bytes: source.length });
    if (!quiet) console.log(`  生成 vendor/${basename(file)}  ←  ${rel}  [${names.join(', ')}]`);
  }

  // 汇总入口：页面只 import 这一个
  const lines = made
    .map((m) => `export * from './${m.file}';`)
    .join('\n');
  writeFileSync(
    join(VENDOR_DIR, 'engines.js'),
    `// AUTO-GENERATED —— 汇总入口。顺序与 manifest.json 一致（顺序敏感）。\n${lines}\n`,
    'utf8',
  );

  return { made, missing };
}

// 直接执行时打印结果
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  console.log('生成引擎包装 →', VENDOR_DIR);
  const { made, missing } = generate();
  console.log(`\n完成：${made.length} 个文件`);
  if (missing.length) {
    console.log('跳过：' + missing.join('、'));
    process.exit(1);
  }
}
