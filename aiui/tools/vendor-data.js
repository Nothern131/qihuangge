// 把项目根的数据文件内嵌成 aiui/ 内部的 ES 模块。
//
// 和 tools/vendor-engines.js 是同一个问题的两种形态：
// .aix 只收工程根（aiui/）以内的文件，而古籍条文在 ../static/data/ 里。
// 设备上 import 不进来，运行时也没有文件系统可读——只能内嵌。
//
// 原始 JSON 一个字节都不改，生成物里记下源文件哈希。
// 这样「源文件改了但忘了重跑生成器」会立刻被测出来，
// 而不是等到设备上数据和测试数据悄悄不一致——那种漂移不报错，只出错。
//
// 用法：node tools/vendor-data.js

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const HERE = dirname(fileURLToPath(import.meta.url));
const AIUI_ROOT = resolve(HERE, '..');
const PROJECT_ROOT = resolve(AIUI_ROOT, '..');
const VENDOR_DIR = join(AIUI_ROOT, 'vendor');

const sha256 = (s) => createHash('sha256').update(s, 'utf8').digest('hex');

/** 要内嵌的数据文件。key 是导出名，path 相对项目根。 */
export const DATA_FILES = [
  { name: 'ANCIENT_TEXTS', path: 'static/data/ancient_texts.json' },
];

export function generateData({ quiet = false } = {}) {
  if (!mkdirSync(VENDOR_DIR, { recursive: true })) { /* 已存在 */ }
  const made = [];
  const missing = [];

  for (const f of DATA_FILES) {
    const abs = join(PROJECT_ROOT, f.path);
    let raw;
    try {
      raw = readFileSync(abs, 'utf8');
    } catch (err) {
      missing.push(`${f.path}（读不到）`);
      continue;
    }
    let parsed;
    try {
      parsed = JSON.parse(raw);
    } catch (err) {
      missing.push(`${f.path}（不是合法 JSON）`);
      continue;
    }
    const arr = Array.isArray(parsed) ? parsed : [];
    if (arr.length === 0) {
      // 空数据不要生成。生成一个空数组会让「查不到原文」看起来像「本来就没有」。
      missing.push(`${f.path}（不是非空数组）`);
      continue;
    }

    const file = join(VENDOR_DIR, 'ancient-texts.js');
    writeFileSync(file, `// AUTO-GENERATED by tools/vendor-data.js —— 不要手改，改源文件后重跑生成器。
// 源文件：${f.path}
// 源文件 sha256：${sha256(raw)}
// 条数：${arr.length}
//
// 为什么内嵌：.aix 只收 aiui/ 以内的文件，设备上没有文件系统可读项目根的 JSON。

export const ${f.name}_SOURCE = ${JSON.stringify(f.path)};
export const ${f.name}_SHA256 = ${JSON.stringify(sha256(raw))};
export const ${f.name}_COUNT = ${arr.length};
export const ${f.name} = ${JSON.stringify(arr, null, 0)};
`, 'utf8');
    made.push({ name: f.name, path: f.path, count: arr.length, sha256: sha256(raw), file: 'ancient-texts.js' });
    if (!quiet) console.log(`  生成 vendor/ancient-texts.js  ←  ${f.path}（${arr.length} 条）`);
  }

  return { made, missing };
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  console.log('生成数据模块 →', VENDOR_DIR);
  const { made, missing } = generateData();
  console.log(`\n完成：${made.length} 个文件`);
  if (missing.length) {
    console.log('跳过：' + missing.join('、'));
    process.exit(1);
  }
}
