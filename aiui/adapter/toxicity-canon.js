for (const h of YOU) INDEX.set(h, '有毒');
for (const h of XIAO) INDEX.set(h, '小毒');

/** 药典名单的全部药名（供词表与测试使用）。 */
export const CANON_HERBS = [...INDEX.keys()];

/** 三个等级各多少味，测试拿它守「名单没被改小」。 */
export const CANON_SIZE = { 大毒: DAY.length, 有毒: YOU.length, 小毒: XIAO.length, total: INDEX.size };

/** 规整药名：别名归正名。 */
export function normalizeToxin(name) {
  const h = String(name || '').trim();
  return ALIASES[h] || h;
}

/**
 * 查一味药的毒性分级。
 *
 * 返回三种形态，调用方必须分开处理——它们的含义完全不同：
 *   { kind: 'canon',    level, text }  药典名单里有，照答
 *   { kind: 'offMarket', text }        已取消药用标准，比有毒更重
 *   { kind: 'extra',    level, text }  药典未收载但公认有毒
 *   null                               名单里没有
 *
 * 返回 null 时**不能**说「无毒」。名单里没有只说明药典没把它列为毒性药材，
 * 不说明它安全——这两件事在这个应用里被混过一次（「查不到 = 可以吃」），
 * 后果是把假阴性包装成了安全结论。
 */
export function toxicityOf(name) {
  const h = normalizeToxin(name);
  const level = INDEX.get(h);
  if (level) {
    return {
      kind: 'canon',
      level,
      text: `${h}在《中国药典》里标为「${level}」`,
    };
  }
  if (OFF_MARKET[h]) return { kind: 'offMarket', text: OFF_MARKET[h] };
  if (EXTRA[h]) return { kind: 'extra', level: EXTRA[h].level, text: EXTRA[h].why };
  return null;
}

