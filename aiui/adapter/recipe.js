/**
 * 「这个药怎么入口」——用法术语白话化 + 古籍食治方挑选。
 *
 * 为什么单独一层：用户拿到「酸枣仁 10~15g」之后的下一个问题一定是
 * 「怎么弄着吃」，而药典只写重量不写做法。这一层负责把两件事补齐：
 *   ① 药典用法里的煎服术语翻成人话（先煎/研末/烊化——不是医学判断，
 *      是行业通用术语解释，不改数据内容）
 *   ② 从《本草纲目》附方里挑出**食治类**（粥/羹/汁/酒等入口做法），
 *      治疗方（汤剂丸散）一律不展示
 *
 * 判定为什么要严：实测里百合抽到「百合知母汤︰治伤寒后百合病…煮取一升…分服」——
 * 那是煎药，不是做饭。照做要出事。所以宁可少给，不能给错。
 */

/** 入口做法：粥/羹/饭/汁/酒/生食/炒食这类真能端上桌的。 */
const EDIBLE_RE = /粥|羹|作饭|做饭|煮食|蒸食|炒食|生食|取汁|绞汁|擂汁|浸酒|酿酒|拌食|蜜煎|煨食|醋浸|作膳食|啖|嚼/;

/**
 * 治疗方特征：煎剂的固定写法。
 * 「煮取X升」「分服」「每服」「方寸匕」「温服」是汤剂的标志，出现就说明这是药不是饭。
 * 方名带「汤/散/丸」的也算——那些要按方抓药，不是厨房能做的。
 */
const REMEDY_RE = /煮取.{0,4}升|分服|煎服|温服|每服|方寸匕|去滓|日[一二三四五]服|为散|汤[︰：]|散[︰：]|丸[︰：]|〔汤〕|〔散〕|〔丸〕|水[一二三四五六七八九十]+分|煎[一二三四五六七八九十]+分/;

/** 一句里出现这些，说明是外用（敷/涂/熏洗），不是吃。 */
const EXTERNAL_RE = /敷|涂|搽|熏洗|熏蒸|贴|掺|点眼|吹鼻|灌肠|洗眼/;

/**
 * 起头就是一个量词（「一盏，粳米半升…」），说明前半句在切分时被切走了。
 * 这种残句照做会缺料，宁可不要。
 */
const ORPHAN_RE = /^[一二三四五六七八九十半]?[盏升合两钱斤个枚片条只撮把碗杯][，,]/;

/** 书名截断（「寇氏《衍义」）——出处不完整等于没有出处。 */
function cleanSrc(src) {
  const s = String(src || '').trim();
  if (!s) return '';
  const open = (s.match(/《/g) || []).length;
  const close = (s.match(/》/g) || []).length;
  if (open !== close) return '';
  return s.replace(/^并/, '').trim();
}

/**
 * 从附方里挑一条最适合展示的食治方。返回 null 表示没有可展示的。
 *
 * 实测踩过的坑（都写进判定里了）：
 *   · 百合知母汤「治伤寒后百合病…煮取一升…分服」——煎药不是做饭
 *   · 决明子「为末，每食后粥饮服方寸匕」——药粉冲服，不是菜
 *   · 莲藕「一盏，粳米半升，以水煮粥」——前半句被切走，照做缺料
 *   · 生姜「——《寇氏《衍义」——书名截断，来源不可查
 * 宁可少给，不能给错：一条都不合格就返回 null，由上层说「这味没有可用的食疗方」。
 */
export function pickRecipe(item) {
  const list = (item && item.fufang) || [];
  const scored = [];
  for (const f of list) {
    const t = String(f.text || '').trim();
    if (!t || t.length < 10) continue;
    if (!EDIBLE_RE.test(t)) continue;          // 不是入口做法
    if (REMEDY_RE.test(t)) continue;           // 是汤剂/丸散
    if (EXTERNAL_RE.test(t)) continue;         // 外用
    if (ORPHAN_RE.test(t)) continue;           // 残句（以量词开头）
    // 粘连条（多道方被切在一起）只取第一句：第二句起往往换了方子换了用法，
    // 一起展示等于把两个方子拼成一个，用户照着做会出错。
    const first = t.split('。')[0];
    if (first.length < 10) continue;
    if (ORPHAN_RE.test(first)) continue;
    scored.push({
      text: first + '。',
      src: cleanSrc(f.src),
      len: first.length,
    });
  }
  if (!scored.length) return null;
  // 短的优先（屏幕只有两行），带出处的优先（来源可查）
  scored.sort((a, b) => (a.len - b.len) || (a.src ? -1 : 1));
  return scored[0];
}

/**
 * 药典「【用法与用量】」的白话解读。
 *
 * 只解释**做法术语**，不解释剂量、不给个人建议：
 * 「先煎」是先把这味煮 20~30 分钟，「烊化」是单独加热化开——
 * 这些是中药行业通用定义，翻成人话不构成新的判断。
 * 剂量区间原样保留（那本来就是药典写的），只加一句遵医嘱。
 */
const TERMS = [
  { re: /先煎/, say: '先煎＝这味先下锅煮 20~30 分钟，再放别的' },
  { re: /后下/, say: '后下＝等其他药快好了最后 5~10 分钟再放' },
  { re: /包煎/, say: '包煎＝用纱布包起来煮，免得糊锅或呛嗓子' },
  { re: /烊化/, say: '烊化＝单独加热化开，再兑进煮好的药里' },
  { re: /冲服/, say: '冲服＝磨成粉，用温水或煮好的药汤冲开喝' },
  { re: /研末|为末|末服/, say: '研末＝磨成细粉再吃' },
  { re: /煎汤|水煎/, say: '煎汤＝加水煮开，喝煮出来的汤' },
  { re: /炖/, say: '炖＝隔水或小火长时间煮，适合根茎类' },
  { re: /泡服|焗服|代茶/, say: '泡服＝开水冲泡当茶喝，不用煮' },
  { re: /生用|鲜品/, say: '生用＝不加热，直接吃或榨汁' },
];

/**
 * 把一条药典用法翻成「人话版」。没有命中术语就返回空串——
 * 上层只在有解释时才加这一句，不硬凑。
 */
export function explainUsage(dosage) {
  const d = String(dosage || '');
  if (!d) return '';
  const hits = TERMS.filter((t) => t.re.test(d)).map((t) => t.say);
  return hits.slice(0, 2).join('；');
}

/** 剂量部分（去掉做法术语），用于「药典写的量是 X」。 */
export function dosageOnly(dosage) {
  const d = String(dosage || '').trim();
  // 取第一个分句里带数字的部分；没有数字就原样返回（可能是「适量」）
  const m = d.match(/^[^，。；]*\d[^，。；]*/);
  return (m ? m[0] : d.split(/[，。；]/)[0] || '').trim();
}

// ───────────────────────── 食疗本草：怎么做着吃 ─────────────────────────

import { shiliaoOf, SHILIAO_SOURCE, SHILIAO_NOTE } from './shiliao-canon.js';

/**
 * 做法动词。命中才说明这一段在讲「怎么弄」，不是单纯讲功效。
 * 「和羊肉作羹」「蒸食」「代茶煮汁」——这些是厨房动作，用户照着能做。
 */
const COOK_VERB_RE = /熟煮|煮汁|煮食|作羹|作粉|作粥|作饭|和面|生食|蒸食|蒸过|和蜜|与蜜|浸酒|酿酒|炒食|炒香|代茶|捣汁|绞汁|研为泥|和.{1,6}(作|食|煎)|煎汤|拌食|煨|熬/;

/** 外用动作：出现在同一句里就说明这句不是吃的。 */
const TOPICAL_RE = /敷|涂|搽|点之|贴|熏洗|塞耳|塞鼻/;

/**
 * 病名/症状词：出现说明这句是「治某个病」的方子，不是「这东西怎么吃」。
 *
 * 实测踩到的：用户问便秘，蜂蜜挑到「血刺腹痛及赤白痢，则生捣地黄汁，
 * 和蜜一大匙，服即下」——那是治痢疾的方子，和便秘无关，照做还有风险。
 * 通用做法（「熟煮和蜜，或为汤煎，或为粉，并佳」）不含病名，靠这条能分开。
 */
const ILLNESS_RE = /痢|疟|疮|吐血|咳|喘|心痛|腹痛|头疼|头痛|肿|疽|痈|疳|瘕|痞|霍乱|伤寒|中风|疥|癣|痔|瘘|淋|崩|带下|惊|痫|蛊|疸|痿|痹|癥|癖|噎|膈|反胃|消渴|霍乱|坠|伤折|金疮|犬咬|蛇咬|蛊毒/;

/** 炮制词：说的是怎么处理药材（炙/煅/烧），不是怎么吃进嘴里。 */
const PREP_RE = /炙|炮|煅|烧存性|炒炭|焙|晒干|阴干|为末|锉|切片/;

/** 服药语气：调服/送下/吞之——这是在吃药，不是在吃饭。 */
const MEDICINE_RE = /调服|送下|吞之|饮下|汤下|酒下|米饮下|服之即|立止|立效|神效/;

/** 功效句：以功效动词起头或明确带「主治」。兜底只收这种。 */
const EFFECT_RE = /^(主|治|疗|补|益|养|安|除|止|利|润|通|和|调|去|消|解|明|强|温)/;

/** 剥掉部位前缀（「叶∶主明目」→「主明目」），只为判定用，展示仍用原文。 */
function barePart(p) {
  return String(p).replace(/^(叶及子|根及叶|白皮|叶|子|根|皮|花|茎|核|仁|汁|苗|节|实|枝|心)∶/, '');
}

/** 考据/体例语：讲产地、别名、仙方、校勘——不是功效也不是做法。 */
const META_RE = /^又，|案经|药家|仙方|世人|凡[^，。]{0,6}[者∶]|此物|谨按|按∶|〔|出《|见《/;

/** 古汉语做法词的白话注（通用词义，不改原文）。 */
const GLOSS = [
  [/作羹/, '作羹＝煮成浓汤'],
  [/作粉/, '作粉＝磨成粉'],
  [/代茶/, '代茶＝当茶泡水喝'],
  [/和蜜|与蜜/, '和蜜＝加蜂蜜拌'],
  [/研为泥/, '研为泥＝捣成糊'],
  [/煮汁饮|煮汁/, '煮汁＝煮出水来喝'],
  [/和面/, '和面＝掺进面粉里'],
];

/**
 * 从《食疗本草》里挑一句「怎么做着吃」。
 *
 * 比本草纲目附方靠谱的地方：附方是治病方剂（「为末，每服二钱」），
 * 这本书每条就是「这物怎么吃、吃了有什么用」——薯蓣「熟煮和蜜，
 * 或为汤煎，或为粉，并佳」，这是厨房里真能照做的话。
 *
 * 返回 null 表示书里没这味，或这味只有功效没写做法。
 */
export function pickShiliao(name) {
  const item = shiliaoOf(name);
  if (!item) return null;
  const cands = [];
  for (const p of item.paras) {
    // 段里可能第一句讲功效、第二句才讲做法，所以逐句挑
    for (const raw of String(p).split('。')) {
      let s = raw.trim();
      if (s.length < 8) continue;
      if (!COOK_VERB_RE.test(s)) continue;
      if (TOPICAL_RE.test(s)) continue;
      if (ILLNESS_RE.test(s)) continue;      // 治病方，不是通用吃法
      if (PREP_RE.test(s)) continue;         // 炮制，不是入口方式
      if (MEDICINE_RE.test(s)) continue;     // 服药语气
      // 含剂量的（「日一颗」可以留，「二钱」这类汤剂量不留）
      if (/\d+\s*(钱|两|分|铢)/.test(s) && !/颗|枚|片/.test(s)) continue;
      // 「叶∶主明目」这类部位前缀：判定功效句时要剥掉，展示时保留原文。
      s = s.replace('∶', '：');
      // 「主心急黄，蒸过蜜和食之」：前半是功效，后半才是做法，剥掉前半。
      // 不剥的话播报出来像在念病名，用户听不出「怎么吃」。
      const m = s.match(/^(?:主|治|疗)[^，]{2,14}[，,](.{6,})$/);
      if (m && COOK_VERB_RE.test(m[1])) s = m[1];
      cands.push(s);
    }
  }
  if (!cands.length) {
    // 没做法但有效用句：照录功效，由上层标明「书里只说功效」。
    // 兜底也要过同样的筛——实测牡蛎取到「火上炙，令沸」（炮制），
    // 屏幕上出现这句等于什么都没说。
    const use = item.paras.find((p) => p.length >= 10
      && !PREP_RE.test(p) && !TOPICAL_RE.test(p) && !ILLNESS_RE.test(p)
      && !META_RE.test(p) && (EFFECT_RE.test(barePart(p)) || /主治|补|益/.test(p)));
    if (!use) return null;
    const first = String(use).split('。')[0].trim();
    if (first.length < 4 || META_RE.test(first)) return null;
    return {
      text: first + '。',
      gloss: '',
      book: SHILIAO_SOURCE,
      canon: item.name,
      asked: item.asked || '',
      nature: item.nature || '',
      cookable: false,
    };
  }
  // 先剔掉警告句，再按长度挑。
  // 「和面作，则微动气」这类是在说副作用，不是教怎么做——实测山药
  // 因为这句最短被选中，播报出来像在劝阻。推荐语气的优先。
  const WARN_RE = /不可(多)?食|不宜|不堪|伤神|动气|少智|有毒|令人.{0,4}(胀|泄|吐)|损人|切忌/;
  const GOOD_RE = /并佳|尤佳|尤善|甚补|相宜|益人|良|妙|补益/;
  const usable = cands.filter((c) => !WARN_RE.test(c));
  const pool = usable.length ? usable : cands;
  pool.sort((a, b) => (GOOD_RE.test(b) ? 1 : 0) - (GOOD_RE.test(a) ? 1 : 0)
    || a.length - b.length);
  const best = pool.find((c) => c.length <= 52) || pool[0];
  const text = best.length > 56 ? best.slice(0, 54) + '…' : best + '。';
  const g = GLOSS.find(([re]) => re.test(best));
  return {
    text,
    gloss: g ? g[1] : '',
    book: SHILIAO_SOURCE,
    note: SHILIAO_NOTE,
    canon: item.name,
    asked: item.asked || '',
    nature: item.nature || '',
    cookable: true,
  };
}

