/**
 * 别名的展开方向：用户/歌诀的说法 → 药典的写法。
 *
 * 不展开就会漏。「乌头反半夏」是最常见的问法之一，而药典里没有「乌头」这一条——
 * 它把川乌、草乌分开写，各自的【注意】里都列着半夏。
 * 同理：歌诀的「朴硝」「牙硝」是药典的芒硝，「牵牛」是牵牛子，
 * 「芍药」分赤芍白芍，「沙参」分南沙参北沙参。
 *
 * 只收确定等价的。像「参」这种能指十几种药材的，一律不收——
 * 展开错了会在两味无关的药上给出禁忌结论，比不答更糟。
 */
const HERB_ALIAS = {
  '乌头': ['川乌', '草乌'],
  '朴硝': ['芒硝'],
  '牙硝': ['芒硝'],
  '沙参': ['南沙参', '北沙参'],
  '芍药': ['白芍', '赤芍'],
  '牵牛': ['牵牛子'],
  '二丑': ['牵牛子'],
};

function variants(h) {
  return Object.prototype.hasOwnProperty.call(HERB_ALIAS, h) ? HERB_ALIAS[h] : [h];
}

/**
 * 查一对药是不是药典列了「不宜同用」。
 *
 * 认不出也不猜：返回 null 表示药典没这两味的记录，
 * 调用方据此说「没查到」，而不是说「可以一起用」——这两句差得很远。
 */
export function canonPair(a, b) {
  const x = String(a || '').trim();
  const y = String(b || '').trim();
  if (!x || !y || x === y) return null;
  // 先按药典写法直接查（最常见的情况），没命中再展开别名。
  const direct = CANON_PAIRS[[x, y].sort().join('|')];
  if (direct) return { ...direct };
  for (const ax of variants(x)) {
    for (const ay of variants(y)) {
      if (ax === ay) continue;
      const hit = CANON_PAIRS[[ax, ay].sort().join('|')];
      if (hit) return { ...hit };
    }
  }
  return null;
}

/** 药典收载的全部配伍禁忌对，给穷举测试用。 */
export function allCanonPairs() {
  return Object.values(CANON_PAIRS).map((v) => v.herbs.slice());
}
