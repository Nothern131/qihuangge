/** 查一味食材。认不出返回 null，调用方据此说「表里没有」，不猜。 */
export function foodOf(name) {
  const k = String(name || '').trim();
  if (!k) return null;
  const real = Object.prototype.hasOwnProperty.call(FOODS, k) ? k : ALIASES[k];
  if (!real || !Object.prototype.hasOwnProperty.call(FOODS, real)) return null;
  return { name: real, ...FOODS[real] };
}

/** 表里所有可识别的写法（正名 + 俗称），给词表用。 */
export function foodWords() {
  return [...Object.keys(FOODS), ...Object.keys(ALIASES)];
}
