// 出处表：一条结论说得出它是谁说的，用户才可能自己去核对。
//
// 为什么不再挂一句统一免责：那句话对用户没有信息量，听三遍就成噪音；
// 更糟的是它把「引书」和「给建议」混成一件事——引书能核对，建议不能。
// 所以这里只做一件事：说清这条从哪来。说来源本身就是边界，
// 因为整句话的主语一直是书，不是「我建议你」。
//
// 三类出处必须分开说，可信度不一样：
//   ① 古籍具名条文 —— 《神农本草经》《本草纲目》《名医别录》
//   ② 当代标准 —— 《中国药典》：毒性分级、性味功效归经、常用量
//   ③ 现代营养学 —— 维生素矿物质的量效与互作，古书里根本没有。
//      把它说成「古人说的」就是造假，所以每条都明写「不是古书」。
//
// 十八反、十九畏的归属最容易说错，这里踩过一次坑：
//   歌诀不在《本草纲目》里。十八反歌诀最早见于金代张从正《儒门事亲》，
//   源头是《神农本草经》「勿用相恶、相反者」；十九畏歌诀最早见于明代刘纯《医经小学》。
//   而李时珍对反药的态度恰恰是「相恶、相反同用者，霸道也，有经有权，在用者识悟尔」——
//   也就是说《本草纲目》认为有条件的可以同用。
//   念成「本草纲目说这两味不能一起用」是错的归属。给错出处比不给更糟：
//   用户按图索骥去翻书，翻不到，之后就再也不信这个助手说的任何一句。

