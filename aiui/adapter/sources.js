/**
 * 拼一行出处。多条命中时走「出处：A、B」句式，
 * 因为连着说两句「这条出自…」听起来像复读，而播报里复读就是噪音。
 */
export function citeLine(keys) {
  const list = [...new Set((keys || []).filter(Boolean))]
    .map((k) => SOURCES[k])
    .filter(Boolean);
  if (list.length === 0) return '';
  if (list.length === 1) return list[0].short;
  return `出处：${list.map((s) => s.tag).join('、')}。`;
}

/**
 * 屏幕用的短标签，不带「这条出自」这类口语句式。
 * 屏幕上一行字的宽度有限，写全句子会把结论本身挤掉，
 * 而结论比出处重要——出处是给愿意再查一步的人留的线索，不是主信息。
 */
export function citeTag(keys) {
  return [...new Set((keys || []).filter(Boolean))]
    .map((k) => SOURCES[k])
    .filter(Boolean)
    .map((s) => s.tag)
    .join('、');
}

/** 屏幕用：长，进 detail / answer，用户能停下来读。 */
export function citeLong(key) {
  const s = SOURCES[key];
  return s ? s.long : '';
}

export function ancientLine(book) {
  return `《${book}》原文在屏幕上。`;
}
