/**
 * 屏幕与播报共用的标签串（不带前缀）。
 * 同一类命中多次时去重，否则会念出「出处：现代营养学资料、现代营养学资料」。
 */
export function citeTag(keys) {
  return [...new Set((keys || []).filter(Boolean))]
    .map((k) => SOURCES[k])
    .filter(Boolean)
    .map((s) => s.tag)
    .join('、');
}

/**
 * 播报末尾的出处行。单一形态：「出处：X。」
 *
 * 为什么不再按条数分两种句式（单条「这条出自…」/ 多条「出处：A、B」）：
 * 两种口吻意味着两条代码路径，改口径时必有一处漏掉；
 * 更要紧的是「这条出自」在替用户解释，而用户不需要被解释，只需要被标明。
 */
export function citeLine(keys) {
  const tag = citeTag(keys);
  return tag ? `出处：${tag}。` : '';
}

/**
 * 没命中时的核查说明。此时不能说「出处」——那是查到了什么的说法，
 * 而这里的实情是查过、没有。混用会让「没查到」听起来像「查到了」，
 * 这恰恰是这个应用最不能出的错。
 *
 * @param {string[]} keys 这次核过的资料
 * @param {string} tail 核对结果，默认「均无记载」
 */
export function citeScope(keys, tail = '均无记载') {
  const tag = citeTag(keys);
  return tag ? `按${tag}核对，${tail}。` : '';
}

/** 屏幕用：长的说明，进 detail / answer，用户能停下来读。 */
export function citeLong(key) {
  const s = SOURCES[key];
  return s ? s.long : '';
}

export function ancientLine(book) {
  return `原文见《${book}》，屏幕上可看`;
}
