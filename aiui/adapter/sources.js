// 出处表：结论说得出它是谁说的，用户才可能自己去核对。
//
// 标注原则（这一版改过的）：
//   出处是结论的组成部分，不是开场承诺，也不是免责话术。所以它只有一个形态：
//   跟在结论后面的一行「出处：X」。不在开场白里预告「每条都会告诉你出处」——
//   那是元信息，用户要的是答案；也不在结尾补「仅供参考」——那是把责任推给用户，
//   而出处是把依据交给用户，两者方向相反。
//
// 三类出处分开标，因为可信度不一样：
//   ① 古籍具名条文 —— 《神农本草经》《本草纲目》《名医别录》
//   ② 当代标准 —— 《中国药典》：毒性分级、性味功效归经、常用量
//   ③ 现代营养学资料 —— 维生素矿物质的量效与互作，古书里没有这一套。
//      单列一类是因为混进古籍就是造假；标注只写类别，不在播报里加解释性长句。
//
// 十八反、十九畏的归属最容易说错，这里踩过一次坑：
//   歌诀不在《本草纲目》里。十八反歌诀最早见于金代张从正《儒门事亲》，
//   源头是《神农本草经》「勿用相恶、相反者」；十九畏歌诀最早见于明代刘纯《医经小学》。
//   而李时珍对反药的态度恰恰是「相恶、相反同用者，霸道也，有经有权，在用者识悟尔」——
//   也就是说《本草纲目》认为有条件的可以同用。
//   标成「本草纲目说这两味不能一起用」是错标。标错比不标更糟：
//   用户按图索骥去翻书，翻不到，之后就再也不信这个助手说的任何一句。

